-- ---------------------------------------------------------------
-- 1. One payment per order (the diagram says one-to-one, but the
--    generated SQL has no UNIQUE on payments.order_id)
-- ---------------------------------------------------------------
ALTER TABLE payments ADD CONSTRAINT uq_payments_order UNIQUE (order_id);

-- ---------------------------------------------------------------
-- 2. Campaign rules
-- ---------------------------------------------------------------
ALTER TABLE campaigns
  ADD CONSTRAINT chk_campaign_price  CHECK (campaign_price > 0 AND platform_charge >= 0),
  ADD CONSTRAINT chk_qty             CHECK (min_quantity >= 1 AND min_quantity <= max_quantity),
  ADD CONSTRAINT chk_order_qty       CHECK (min_order_quantity >= 1
                                            AND min_order_quantity <= max_quantity
                                            AND (max_per_user IS NULL
                                                 OR (min_order_quantity <= max_per_user AND max_per_user <= max_quantity))),
  ADD CONSTRAINT chk_cutoff          CHECK (cancellation_cutoff <= deadline);

-- ---------------------------------------------------------------
-- 3. Product rules
-- ---------------------------------------------------------------
ALTER TABLE products
  ADD CONSTRAINT chk_source  CHECK ((source = 'platform' AND seller_id IS NULL)
                                    OR (source = 'seller' AND seller_id IS NOT NULL)),
  ADD CONSTRAINT chk_prices  CHECK (wholesale_price > 0 AND retail_price > wholesale_price),
  ADD CONSTRAINT chk_stock   CHECK (stock_quantity >= 0);

-- ---------------------------------------------------------------
-- 4. Location rules
-- ---------------------------------------------------------------
ALTER TABLE locations
  ADD CONSTRAINT chk_delivery_fee CHECK (delivery_fee >= 0);

-- ---------------------------------------------------------------
-- 5. Order rules
-- ---------------------------------------------------------------
ALTER TABLE orders
  ADD CONSTRAINT chk_order_quantity    CHECK (quantity >= 1),
  ADD CONSTRAINT chk_order_amounts     CHECK (unit_price > 0 AND platform_charge >= 0 AND logistics_charge >= 0),
  ADD CONSTRAINT chk_delivery_address  CHECK (fulfilment <> 'delivery' OR delivery_address IS NOT NULL),
  ADD CONSTRAINT chk_collection_free   CHECK (fulfilment <> 'collection' OR logistics_charge = 0),
  ADD CONSTRAINT chk_total             CHECK (total_amount = quantity * (unit_price + platform_charge) + logistics_charge);

-- ---------------------------------------------------------------
-- 6. Money that moves must be positive
-- ---------------------------------------------------------------
ALTER TABLE payments    ADD CONSTRAINT chk_payment_amount    CHECK (amount > 0);
ALTER TABLE refunds     ADD CONSTRAINT chk_refund_amount     CHECK (amount > 0);
ALTER TABLE settlements ADD CONSTRAINT chk_settlement_amount CHECK (amount >= 0);

